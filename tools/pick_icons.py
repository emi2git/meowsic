"""Pick a meaningful icon for each song, offline.

1. Tag rules (Christmas -> tree, Musical -> theatre mask, ...).
2. No rule -> a small local text model (model2vec potion-base-8M, in ~/ai/models) compares the
   title with each icon's keywords and takes the closest one if it is close enough.
3. Otherwise a plain icon by type.

Usage: tools/.venv/bin/python tools/pick_icons.py items.json > web/js/item-icons.js
"""
import json, sys, os
import numpy as np
from model2vec import StaticModel

HERE = os.path.dirname(__file__)
VOCAB = json.load(open(os.path.join(HERE, 'icon_vocab.json')))
TAG_RULES = {  # first matching tag wins, in this order
    'Christmas': 'tree-evergreen', 'Frozen': 'snowflake', 'Phantom of the opera': 'ghost', 'Les Miserables': 'sword',
    'Disney': 'castle-turret', 'Anime': 'cloud', 'Musical': 'mask-happy', 'Movie': 'film-strip', 'Classical': 'piano-keys',
    'Children': 'lego-smiley', 'Jazz': 'vinyl-record', 'Rock': 'lightning', 'Country': 'house', 'Ballad': 'heart',
}
DEFAULT = {'sheet': 'file-text', 'score': 'music-notes', 'chords': 'guitar'}
THRESHOLD = 0.35  # cosine similarity needed for the model to override the default

model = StaticModel.from_pretrained('minishlab/potion-base-8M')  # cached in HF_HUB_CACHE (~/ai/models)
names = list(VOCAB)
V = model.encode([VOCAB[n] for n in names])
V /= np.linalg.norm(V, axis=1, keepdims=True)

def pick(item):
    # the title speaks first ("Let It Go" -> snowflake), then tag rules, then the default
    q = model.encode([item['title']])[0]
    q /= np.linalg.norm(q) or 1
    sims = V @ q
    best = int(sims.argmax())
    if sims[best] >= THRESHOLD:
        return names[best], f'title ~ {names[best]} ({sims[best]:.2f})'
    for tag, icon in TAG_RULES.items():
        if tag in item['tags']:
            return icon, f'tag {tag}'
    return DEFAULT[item['kind']], 'default'

items = json.load(open(sys.argv[1]))
out, why = {}, {}
for it in items:
    icon, reason = pick(it)
    out[it['title']] = icon
    why[it['title']] = reason
print('// Generated by tools/pick_icons.py (offline model + tag rules). Do not edit by hand.')
print('export const ITEM_ICONS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';')
json.dump(why, open(os.path.join(HERE, 'icon_reasons.json'), 'w'), ensure_ascii=False, indent=1)
